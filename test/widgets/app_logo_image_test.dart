import 'dart:typed_data';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:banjarabio/widgets/app_logo_image.dart';
import 'package:banjarabio/core/services/app_logo_service.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  group('AppLogoImage Widget Tests', () {
    testWidgets('renders Image.memory when memory logoBytes are cached', (tester) async {
      // 1x1 transparent png byte header
      final fakeBytes = Uint8List.fromList([
        0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D,
        0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
        0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, 0x89, 0x00, 0x00, 0x00,
        0x0A, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00,
        0x05, 0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4, 0x00, 0x00, 0x00, 0x00, 0x49,
        0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
      ]);
      AppLogoService.instance.logoBytes = fakeBytes;

      await tester.pumpWidget(
        const MaterialApp(
          home: Scaffold(
            body: AppLogoImage(width: 50, height: 50),
          ),
        ),
      );

      expect(find.byType(AppLogoImage), findsOneWidget);
      expect(find.byType(Image), findsOneWidget);
    });
  });
}
